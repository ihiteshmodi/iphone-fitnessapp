// Turns tools/anatomy/figure.js into the Swift data file the app draws from, so the HTML mockup and the app
// always use the same shapes.
//   node tools/anatomy/generate-swift.js            writes the file
//   node tools/anatomy/generate-swift.js --check    exits 1 if the file is out of date
const fs = require('fs');
const path = require('path');
const figure = require('./figure.js');

const target = path.join(__dirname, '..', '..', 'src', 'modules', 'planning', 'muscle-anatomy', 'MuscleFigureData.swift');

const quote = (s) => JSON.stringify(s);
const list = (paths, indent) => `[\n${paths.map((p) => `${indent}    ${quote(p)},`).join('\n')}\n${indent}]`;
const dictionary = (parts) =>
  `[\n${Object.entries(parts)
    .map(([part, paths]) => `        ${quote(part)}: ${list(paths, '        ')},`)
    .join('\n')}\n    ]`;

const source = `// Generated by tools/anatomy/generate-swift.js from tools/anatomy/figure.js. Do not edit by hand.
// Shapes are SVG path data (absolute M, C, Z only) in a ${figure.width} x ${figure.height} box; both body halves are already included.

public enum MuscleFigureData {
    public static let width = ${figure.width}.0
    public static let height = ${figure.height}.0

    /// Dim silhouette drawn behind the muscles.
    public static let base: [String] = ${list(figure.base, '    ')}

    /// Muscle shapes seen from the front, keyed by \`MusclePart.rawValue\`.
    public static let front: [String: [String]] = ${dictionary(figure.front)}

    /// Muscle shapes seen from the back, keyed by \`MusclePart.rawValue\`.
    public static let back: [String: [String]] = ${dictionary(figure.back)}
}
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== source) {
    console.error('MuscleFigureData.swift is out of date. Run: node tools/anatomy/generate-swift.js');
    process.exit(1);
  }
  console.log('MuscleFigureData.swift is up to date');
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, source);
  console.log(`wrote ${path.relative(process.cwd(), target)}`);
}
